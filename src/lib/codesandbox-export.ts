/**
 * Build a CodeSandbox "define" URL from the user's component code.
 *
 * CodeSandbox's open-from-URL API takes a base64-encoded JSON object of files
 * in the `parameters` query param. The JSON shape is:
 *
 *   {
 *     "App.js":           { content: "<user code>" },
 *     "index.js":         { content: "<entry that renders App>" },
 *     "package.json":     { content: "<deps>" },
 *     "tailwind.config.js": { content: "<tailwind config>" },
 *     "postcss.config.js":  { content: "<postcss config>" },
 *     "tailwind.css":       { content: "@tailwind base; @tailwind components; @tailwind utilities;" }
 *   }
 *
 * The base64 is standard base64 of the UTF-8 JSON string. The final URL is:
 *
 *   https://codesandbox.io/api/v1/sandboxes/define?parameters=<base64>
 *
 * Refs:
 *   - https://codesandbox.io/docs/getting-started#open-sandbox-from-url
 *   - https://github.com/codesandbox/codesandbox-importers
 *
 * Pure function so we can unit-test the encoding round-trip.
 */

const SANDBOX_BASE = 'https://codesandbox.io/api/v1/sandboxes/define'

const ENTRY_JS = `import React from "react";
import ReactDOM from "react-dom";
import "./tailwind.css";
import App from "./App";

const root = ReactDOM.createRoot(document.getElementById("root"));
root.render(<App />);
`

const PACKAGE_JSON = JSON.stringify(
  {
    name: 'screenshot-to-code-export',
    version: '1.0.0',
    description: 'Generated by Screenshot to Code Converter',
    dependencies: {
      react: '^18.2.0',
      'react-dom': '^18.2.0',
      'react-scripts': '^5.0.0',
    },
    devDependencies: {
      tailwindcss: '^3.4.0',
      postcss: '^8.4.0',
      autoprefixer: '^10.4.0',
    },
    scripts: {
      start: 'react-scripts start',
      build: 'react-scripts build',
    },
  },
  null,
  2,
)

const TAILWIND_CONFIG = `/** @type {import('tailwindcss').Config} */
module.exports = {
  content: ["./src/**/*.{js,jsx,ts,tsx}"],
  theme: { extend: {} },
  plugins: [],
};
`

const POSTCSS_CONFIG = `module.exports = {
  plugins: {
    tailwindcss: {},
    autoprefixer: {},
  },
};
`

const TAILWIND_CSS = `@tailwind base;
@tailwind components;
@tailwind utilities;
`

const INDEX_HTML = `<!DOCTYPE html>
<html lang="en">
  <head>
    <meta charset="utf-8" />
    <meta name="viewport" content="width=device-width, initial-scale=1" />
    <title>Generated Component</title>
  </head>
  <body>
    <div id="root"></div>
  </body>
</html>
`

export interface CodeSandboxFiles {
  [path: string]: { content: string; isBinary?: boolean }
}

/** Build the CodeSandbox `files` object from user code + a component name. */
export function buildSandboxFiles(code: string, componentName = 'GeneratedComponent'): CodeSandboxFiles {
  // Ensure the user code is a valid module: ensure it has an `export default`
  // pointing at the named component (in case the LLM forgot it).
  let appJs = String(code || '')
  if (!/export\s+default/.test(appJs)) {
    appJs = `${appJs}\nexport default ${componentName};\n`
  }
  return {
    'src/App.js': { content: appJs },
    'src/index.js': { content: ENTRY_JS },
    'src/tailwind.css': { content: TAILWIND_CSS },
    'public/index.html': { content: INDEX_HTML },
    'package.json': { content: PACKAGE_JSON },
    'tailwind.config.js': { content: TAILWIND_CONFIG },
    'postcss.config.js': { content: POSTCSS_CONFIG },
  }
}

/** Base64-encode a UTF-8 string. Works in both browser and Node/Bun. */
export function base64Utf8Encode(s: string): string {
  const bytes = new TextEncoder().encode(s)
  // Use Buffer if available (Node/Bun), else browser btoa.
  if (typeof Buffer !== 'undefined') {
    return Buffer.from(bytes).toString('base64')
  }
  let bin = ''
  for (const b of bytes) bin += String.fromCharCode(b)
  return btoa(bin)
}

/** Decode a base64 string back to UTF-8. */
export function base64Utf8Decode(b64: string): string {
  if (typeof Buffer !== 'undefined') {
    return Buffer.from(b64, 'base64').toString('utf-8')
  }
  const bin = atob(b64)
  const bytes = new Uint8Array(bin.length)
  for (let i = 0; i < bin.length; i++) bytes[i] = bin.charCodeAt(i)
  return new TextDecoder().decode(bytes)
}

export function buildCodeSandboxUrl(
  code: string,
  componentName = 'GeneratedComponent',
): string {
  const files = buildSandboxFiles(code, componentName)
  // The CodeSandbox parameters JSON is `{ files: CodeSandboxFiles }` but the
  // documented format uses the top-level as the files map directly. We use
  // the canonical shape documented at
  // https://codesandbox.io/docs/getting-started#define-api
  const json = JSON.stringify({ files })
  const encoded = base64Utf8Encode(json)
  return `${SANDBOX_BASE}?parameters=${encoded}`
}

/** Decode the parameters of a CodeSandbox define URL back into the files object. */
export function decodeCodeSandboxUrl(url: string): { files: CodeSandboxFiles } {
  const idx = url.indexOf('parameters=')
  if (idx < 0) throw new Error('Not a CodeSandbox define URL: missing parameters= param')
  const b64 = decodeURIComponent(url.slice(idx + 'parameters='.length).split('&')[0])
  const json = base64Utf8Decode(b64)
  return JSON.parse(json)
}
